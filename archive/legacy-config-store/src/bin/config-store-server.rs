// Helper functions
fn system_time_to_timestamp(time: &SystemTime) -> prost_types::Timestamp {
    let duration = time.duration_since(std::time::UNIX_EPOCH).unwrap();
    prost_types::Timestamp {
        seconds: duration.as_secs() as i64,
        nanos: duration.subsec_nanos() as i32,
    }
}

fn json_to_struct(json: &serde_json::Value) -> prost_types::Struct {
    match json {
        serde_json::Value::Object(map) => {
            let fields = map
                .iter()
                .map(|(k, v)| (k.clone(), json_value_to_prost_value(v)))
                .collect();
            prost_types::Struct { fields }
        }
        _ => prost_types::Struct {
            fields: BTreeMap::new(),
        },
    }
}

fn json_value_to_prost_value(json: &serde_json::Value) -> prost_types::Value {
    let kind = match json {
        serde_json::Value::Null => prost_types::value::Kind::NullValue(0),
        serde_json::Value::Bool(b) => prost_types::value::Kind::BoolValue(*b),
        serde_json::Value::Number(n) => {
            if let Some(i) = n.as_i64() {
                prost_types::value::Kind::NumberValue(i as f64)
            } else if let Some(f) = n.as_f64() {
                prost_types::value::Kind::NumberValue(f)
            } else {
                prost_types::value::Kind::StringValue(n.to_string())
            }
        }
        serde_json::Value::String(s) => prost_types::value::Kind::StringValue(s.clone()),
        serde_json::Value::Array(arr) => {
            let values = arr.iter().map(json_value_to_prost_value).collect();
            prost_types::value::Kind::ListValue(prost_types::ListValue { values })
        }
        serde_json::Value::Object(_) => prost_types::value::Kind::StructValue(json_to_struct(json)),
    };

    prost_types::Value { kind: Some(kind) }
}

fn struct_to_json(struct_val: &prost_types::Struct) -> serde_json::Value {
    let map: serde_json::Map<String, serde_json::Value> = struct_val
        .fields
        .iter()
        .map(|(k, v)| (k.clone(), prost_value_to_json(v)))
        .collect();

    serde_json::Value::Object(map)
}

fn prost_value_to_json(value: &prost_types::Value) -> serde_json::Value {
    match &value.kind {
        Some(prost_types::value::Kind::NullValue(_)) => serde_json::Value::Null,
        Some(prost_types::value::Kind::BoolValue(b)) => serde_json::Value::Bool(*b),
        Some(prost_types::value::Kind::NumberValue(n)) => serde_json::Number::from_f64(*n)
            .map(serde_json::Value::Number)
            .unwrap_or(serde_json::Value::Null),
        Some(prost_types::value::Kind::StringValue(s)) => serde_json::Value::String(s.clone()),
        Some(prost_types::value::Kind::ListValue(list)) => {
            let values: Vec<serde_json::Value> =
                list.values.iter().map(prost_value_to_json).collect();
            serde_json::Value::Array(values)
        }
        Some(prost_types::value::Kind::StructValue(struct_val)) => struct_to_json(struct_val),
        None => serde_json::Value::Null,
    }
}

#[tokio::main]
async fn main() -> Result<(), Box<dyn std::error::Error>> {
    let matches = Command::new("config-store-server")
        .version("0.1.0")
        .about("Neural Trader Config Store gRPC Server")
        .arg(
            Arg::new("port")
                .short('p')
                .long("port")
                .value_name("PORT")
                .help("Port to listen on")
                .default_value("50051"),
        )
        .arg(
            Arg::new("host")
                .long("host")
                .value_name("HOST")
                .help("Host to bind to")
                .default_value("0.0.0.0"),
        )
        .subcommand(Command::new("health").about("Check server health"))
        .get_matches();

    // Handle health check command
    if let Some(_) = matches.subcommand_matches("health") {
        return handle_health_check().await;
    }

    // Initialize tracing
    tracing_subscriber::registry()
        .with(
            tracing_subscriber::EnvFilter::try_from_default_env()
                .unwrap_or_else(|_| "config_store=info,tower_http=debug".into()),
        )
        .with(tracing_subscriber::fmt::layer())
        .init();

    let port = matches.get_one::<String>("port").unwrap().parse::<u16>()?;
    let host = matches.get_one::<String>("host").unwrap();
    let addr = format!("{}:{}", host, port);

    info!("Starting Config Store gRPC server on {}", addr);

    // Create the service implementation
    let config_service = ConfigStoreServiceImpl::new().await?;
    let management_service = config_service.clone();

    // Create the server
    let server = Server::builder()
        .add_service(ConfigStoreServiceServer::new(config_service))
        .add_service(ConfigManagementServiceServer::new(management_service))
        .serve(addr.parse()?);

    info!("Config Store server listening on {}", addr);

    // Handle graceful shutdown
    tokio::select! {
        result = server => {
            if let Err(e) = result {
                error!("Server error: {}", e);
                return Err(e.into());
            }
        }
        _ = tokio::signal::ctrl_c() => {
            info!("Received shutdown signal");
        }
    }

    info!("Config Store server shutting down");
    Ok(())
}

async fn handle_health_check() -> Result<(), Box<dyn std::error::Error>> {
    // Try to connect to the server
    let port = env::var("CONFIG_STORE_PORT").unwrap_or_else(|_| "50051".to_string());
    let addr = format!("http://127.0.0.1:{}", port);

    info!("Checking health at {}", addr);

    match tonic::transport::Endpoint::from_shared(addr)?
        .connect()
        .await
    {
        Ok(client) => {
            let mut client = ConfigStoreServiceClient::new(client);

            match client.health_check(tonic::Request::new(())).await {
                Ok(response) => {
                    let health = response.into_inner();
                    if health.healthy {
                        info!("Health check passed: {}", health.status);
                        process::exit(0);
                    } else {
                        warn!("Health check failed: {}", health.status);
                        process::exit(1);
                    }
                }
                Err(e) => {
                    error!("Health check RPC failed: {}", e);
                    process::exit(1);
                }
            }
        }
        Err(e) => {
            error!("Failed to connect to server: {}", e);
            process::exit(1);
        }
    }
}
